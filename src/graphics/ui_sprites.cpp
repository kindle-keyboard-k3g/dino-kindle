SpriteMask UiSprites::game_over_banner() {
    return SpriteMask{191, 11, GAME_OVER_BYTES};
}

SpriteMask UiSprites::restart_button() {
    return SpriteMask{36, 32, RESTART_BYTES};
}

SpriteMask UiSprites::score_digit(int32_t digit) {
    const int32_t clamped = std::clamp(digit, 0, 9);
    const size_t offset = static_cast<size_t>(clamped * 17);
    return SpriteMask{10, 13, &SCORE_DIGITS_BYTES[offset]};
}

SpriteMask UiSprites::score_hi() {
    return SpriteMask{20, 13, SCORE_HI_BYTES};
}

const GroundBump* UiSprites::ground_bumps() {
    return GROUND_BUMPS;
}

size_t UiSprites::ground_bump_count() {
    return sizeof(GROUND_BUMPS) / sizeof(GROUND_BUMPS[0]);
}

